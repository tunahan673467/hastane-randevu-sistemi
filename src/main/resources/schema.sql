CREATE TABLE IF NOT EXISTS kilit (id INT PRIMARY KEY);
MERGE INTO kilit KEY(id) VALUES(1);

CREATE TABLE IF NOT EXISTS kurum (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ad VARCHAR UNIQUE NOT NULL, ac TIME NOT NULL, kapa TIME NOT NULL, CHECK (ac < kapa)
);
CREATE TABLE IF NOT EXISTS bolum (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kurum BIGINT REFERENCES kurum NOT NULL, ad VARCHAR NOT NULL, UNIQUE(kurum, ad)
);
CREATE TABLE IF NOT EXISTS hizmet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bolum BIGINT REFERENCES bolum NOT NULL, ad VARCHAR NOT NULL,
    sure INT CHECK(sure BETWEEN 1 AND 1440) NOT NULL,
    ucret DECIMAL(12,2) CHECK(ucret >= 0) NOT NULL, UNIQUE(bolum, ad)
);
CREATE TABLE IF NOT EXISTS kisi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hesap VARCHAR UNIQUE NOT NULL, ad VARCHAR NOT NULL, parola VARCHAR NOT NULL,
    rol VARCHAR NOT NULL, bolum BIGINT REFERENCES bolum, uzmanlik VARCHAR
);
CREATE TABLE IF NOT EXISTS sunum (
    kisi BIGINT REFERENCES kisi, hizmet BIGINT REFERENCES hizmet, PRIMARY KEY(kisi,hizmet)
);
CREATE TABLE IF NOT EXISTS mesai (
    kisi BIGINT REFERENCES kisi, gun DATE NOT NULL, ilk TIME NOT NULL, son TIME NOT NULL,
    CHECK(ilk < son), PRIMARY KEY(kisi,gun,ilk,son)
);
CREATE TABLE IF NOT EXISTS randevu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hasta BIGINT REFERENCES kisi NOT NULL, personel BIGINT REFERENCES kisi NOT NULL,
    hizmet BIGINT REFERENCES hizmet NOT NULL, gun DATE NOT NULL,
    ilk TIME NOT NULL, son TIME NOT NULL, ucret DECIMAL(12,2) NOT NULL, durum VARCHAR NOT NULL
);
